def row_of(key: str) -> int:
    """Номер строки Excel для ключа (заголовок — строка 1)."""
    return next(i for i, c in enumerate(CASES, start=2) if c[0] == key)


def build(path: Path) -> Path:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Заявки"
    ws.append(["Имя", "Телефон", "Дата заявки", "Источник"])
    for _key, name, phone, dt, source, _exp in CASES:
        ws.append([name, phone, dt, source])
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


